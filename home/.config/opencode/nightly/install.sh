#!/usr/bin/env bash
#
# Install / uninstall the opencode nightly systemd user timer.
#
# The unit files live next to this script; they are symlinked into
# ~/.config/systemd/user so there is a single source of truth.
#
# Usage:
#   ./install.sh              # install, enable and start the timer
#   ./install.sh uninstall    # stop, disable and remove the units
set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
UNIT_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/systemd/user"
SERVICE="opencode-nightly.service"
TIMER="opencode-nightly.timer"
ENV_FILE="$SCRIPT_DIR/env"

log() { printf '[install] %s\n' "$*"; }

resolve_opencode() {
  if [[ -n "${OPENCODE_BIN:-}" && -x "${OPENCODE_BIN}" ]]; then
    printf '%s\n' "$OPENCODE_BIN"
    return
  fi
  local found
  if found="$(command -v opencode 2>/dev/null)"; then
    printf '%s\n' "$found"
    return
  fi
  printf '%s\n' "/snap/bin/opencode"
}

write_env_file() {
  local bin
  bin="$(resolve_opencode)"
  {
    printf '# Generated by install.sh - do not edit by hand.\n'
    printf 'OPENCODE_BIN=%s\n' "$bin"
  } >"$ENV_FILE"
  log "opencode binary: $bin"
}

install_units() {
  mkdir -p "$UNIT_DIR"
  ln -sfn "$SCRIPT_DIR/$SERVICE" "$UNIT_DIR/$SERVICE"
  ln -sfn "$SCRIPT_DIR/$TIMER" "$UNIT_DIR/$TIMER"
  log "linked units into $UNIT_DIR"

  systemctl --user daemon-reload

  if command -v loginctl >/dev/null 2>&1; then
    if loginctl enable-linger "$USER" 2>/dev/null; then
      log "linger enabled for $USER"
    else
      log "warning: could not enable linger (timer only runs while logged in)"
    fi
  fi

  systemctl --user enable --now "$TIMER"
  log "timer enabled and started"
  systemctl --user --no-pager list-timers "$TIMER" || true
}

uninstall_units() {
  systemctl --user disable --now "$TIMER" 2>/dev/null || true
  rm -f "$UNIT_DIR/$SERVICE" "$UNIT_DIR/$TIMER"
  systemctl --user daemon-reload
  log "timer disabled and units removed"
}

case "${1:-install}" in
  install) write_env_file; install_units ;;
  uninstall) uninstall_units ;;
  *)
    printf 'Usage: %s [install|uninstall]\n' "$0" >&2
    exit 2
    ;;
esac
